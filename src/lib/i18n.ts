export const DICT: Record<Lang, Partial<Dict>> = { en: en as unknown as Dict, ur, ar, es, fr };

// anything a language does not define falls back to English
export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>) {
  let s = (DICT[lang]?.[key] ?? (en as unknown as Dict)[key] ?? key) as string;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
